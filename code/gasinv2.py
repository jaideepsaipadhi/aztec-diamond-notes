"""
The full-plane gas inverse with the fundamental-domain bookkeeping done, not
guessed.

TWO FAILED ATTEMPTS PRECEDE THIS, both in gasinv.py:

  * exponents = the e1/e2 step counts (u, v).  Wrong sign alternation and
    roughly double the true decay rate.
  * exponents = u // 2, v // 2.  Correct on the diagonal ray that was the only
    thing ever checked; wrong by >10% on 27 of 36 offsets in [-5,5]^2, with
    errors that do not shrink with n.

Neither performs the split the contour integral actually requires:

    y - x  =  (translation by whole fundamental domains)  +  (offset within one)

the first giving z^u w^v, the second selecting the entry of K(z,w)^{-1}.
Floor division is not that split; it discards the within-domain part instead of
routing it to the matrix index.

THE PERIOD LATTICE.  The edge directions E1 = (1,1), E2 = (-1,1) are NOT
translations of the vertex set -- E2 maps a black vertex to a white one -- and
bclass depends on (x1 + x2) mod 4, which E1 shifts by 2.  So the translations
preserving both the bipartite classes and the weights are generated by

    2*E1 = (2, 2)   and   2*E2 = (-2, 2)

a cell of area 8 containing 4 vertices (2 black, 2 white), which is what makes
K(z,w) a 2x2 matrix.  Hence z and w are conjugate to 2*E1 and 2*E2, and
a displacement (c1, c2) is p*(2,2) + q*(-2,2) with

    p = (c1 + c2)/4,      q = (c2 - c1)/4

integral only when c1 +- c2 == 0 mod 4.  That is exactly the condition the
within-domain offset has to absorb.

THE ALGORITHM.  Fix one representative per class:

    white class 0: (1, 0)    white class 1: (1, 2)
    black class 0: (0, 1)    black class 1: (2, 1)

(classes by gasinv.cls, i.e. ((x1+x2) mod 4 - 1)//2.)  For white x of class a1
and black y of class a2, write x = repW(a1) + T and y = repB(a2) + T' with T, T'
in the period lattice; then

    p*(2E1) + q*(2E2)  =  (y - x) - (repB(a2) - repW(a1))

whose right-hand side is guaranteed to lie in the period lattice, so p and q
come out integral.  The class pair (a1, a2) picks the entry of K(z,w)^{-1} as
before.  Nothing is rounded or truncated anywhere.

This is checked by gasinv_validate against every offset, not along a ray.
"""
import numpy as np

REP_W = {0: (1, 0), 1: (1, 2)}
REP_B = {0: (0, 1), 1: (2, 1)}


def cls(v):
    """0 or 1 according to (x1 + x2) mod 4; matches twoperiodic.bclass."""
    return ((v[0] + v[1]) % 4 - 1) // 2


def domain_translation(x, y):
    """(p, q, a1, a2) for white x, black y -- or None if inconsistent.

    p, q count whole fundamental domains; a1, a2 are the class indices.
    """
    a1, a2 = cls(x), cls(y)
    c1 = (y[0] - x[0]) - (REP_B[a2][0] - REP_W[a1][0])
    c2 = (y[1] - x[1]) - (REP_B[a2][1] - REP_W[a1][1])
    if (c1 + c2) % 4 or (c2 - c1) % 4:
        return None                     # not in the period lattice: a bug
    return (c1 + c2) // 4, (c2 - c1) // 4, a1, a2


def gas_inverse(x, y, a, N=600):
    """K^{-1}_{gas}(x, y) for white x, black y, on the full plane."""
    t = domain_translation(x, y)
    if t is None:
        raise ValueError(f"{x}, {y} not related by a period-lattice translation")
    p, q, a1, a2 = t
    th = 2 * np.pi * np.arange(N) / N
    z = np.exp(1j * th)
    w = np.exp(1j * th)
    Z, W = np.meshgrid(z, w, indexing='ij')
    P = -2 - 2 * a ** 2 - a / W - a * W - a / Z - a * Z
    if (a1, a2) == (0, 0):
        num = 1j * (a + W)
    elif (a1, a2) == (0, 1):
        num = -(a + Z)
    elif (a1, a2) == (1, 0):
        num = -(a + 1 / Z)
    else:
        num = 1j * (a + 1 / W)
    return (num / P * Z ** p * W ** q).mean()


if __name__ == "__main__":
    from twoperiodic import kasteleyn, vertices

    a = 0.7
    print("fundamental-domain split: sanity before validation\n")
    print("  every white/black pair must be related by a period-lattice")
    print("  translation once the class representatives are removed:")
    bad = 0
    for n in (16,):
        W, B = vertices(n)
        for x in W[:400]:
            for y in B[:40]:
                if domain_translation(x, y) is None:
                    bad += 1
    print(f"    inconsistent pairs: {bad}  (must be 0)\n")

    print("  broad offset check against the exact inverse, a = 0.7:")
    for n in (32, 48):
        W, B = vertices(n)
        wi = {v: i for i, v in enumerate(W)}
        bi = {v: i for i, v in enumerate(B)}
        Kinv = np.linalg.inv(kasteleyn(n, a))
        c = min(B, key=lambda t: (t[0] - n) ** 2 + (t[1] - n) ** 2)
        errs = []
        for d1 in range(-5, 6):
            for d2 in range(-5, 6):
                w0 = (c[0] + d1, c[1] + d2)
                if w0 not in wi:
                    continue
                ex = Kinv[wi[w0], bi[c]]
                gf = gas_inverse(w0, c, a)
                if abs(ex) < 1e-10 and abs(gf) < 1e-10:
                    continue
                errs.append(abs(ex - gf) / max(abs(ex), 1e-30))
        errs = np.array(errs)
        print(f"    n={n}: {len(errs)} offsets, median rel err "
              f"{np.median(errs):.4f}, max {errs.max():.4f}, "
              f">10%: {(errs > 0.10).sum()}")
